def page_frontmatter(slug: str) -> dict[str, str]:
    matches = list(PAGES_DIR.glob(f"*/{slug}.md"))
    if not matches:
        return {}
    text = matches[0].read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    block = text.split("---", 2)[1]
    out: dict[str, str] = {}
    for line in block.splitlines():
        m = re.match(r"^([a-z_]+):\s*(.*)$", line)
        if m:
            out[m.group(1)] = m.group(2).strip().strip("'\"")
    return out


def measure_csv(path: Path) -> tuple[int, list[str], str]:
    with path.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        columns = list(reader.fieldnames or [])
        rows = 0
        latest = ""
        date_cols = [c for c in DATE_COLUMNS if c in columns]
        for row in reader:
            rows += 1
            for col in date_cols:
                value = (row.get(col) or "").strip()[:10]
                if ISO_DATE.match(value) and value > latest:
                    latest = value
    return rows, columns, latest


def measure_geojson(path: Path) -> tuple[int, list[str], str]:
    data = json.loads(path.read_text(encoding="utf-8"))
    features = data.get("features", [])
    keys: dict[str, None] = {}
    for feat in features:
        for key in (feat.get("properties") or {}):
            keys.setdefault(key, None)
    return len(features), sorted(keys), ""


def build_catalog() -> dict:
    entries = []
    declared = list(DATASETS) + [d for d in OPTIONAL_DATASETS if (ROOT / d[1]).exists()]
    for ds_id, rel, title, domain, companion, schema, summary in declared:
        path = ROOT / rel
        if not path.exists():
            raise SystemExit(f"FAIL: cataloged dataset missing on disk: {rel}")
        if domain not in DOMAINS:
            raise SystemExit(f"FAIL: unknown domain {domain} for {ds_id}")
        fmt = "geojson" if path.suffix == ".geojson" else "csv"
        rows, columns, latest = measure_geojson(path) if fmt == "geojson" else measure_csv(path)
        front = page_frontmatter(companion)
        if not front:
            raise SystemExit(f"FAIL: companion page not found for {ds_id}: {companion}")
        verified_basis = "row verification dates" if latest else "companion page review date"
        if not latest:
            latest = front.get("reviewed") or front.get("updated") or ""
        entries.append({
            "id": ds_id,
            "title": title,
            "domain": domain,
            "path": rel,
            "format": fmt,
            "rows": rows,
            "columns": len(columns),
            "column_names": columns,
            "schema_path": schema,
            "companion_page_slug": companion,
            "last_verified": latest,
            "last_verified_basis": verified_basis,
            "license": LICENSE,
            "summary": summary,
        })
    return {
        "version": 1,
        "generator": "scripts/build_dataset_catalog.py",
        "license_note": LICENSE,
        "domains": DOMAINS,
        "counts": {
            "datasets": len(entries),
            "csv": sum(1 for e in entries if e["format"] == "csv"),
            "geojson": sum(1 for e in entries if e["format"] == "geojson"),
        },
        "datasets": entries,
    }


def render_block(catalog: dict) -> str:
    counts = catalog["counts"]
    lines = [START, "", f"**{counts['datasets']} datasets** — {counts['csv']} CSV tables and {counts['geojson']} GeoJSON map layers. Counts are measured from the files on every build.", ""]
    for domain, label in DOMAINS.items():
        rows = [e for e in catalog["datasets"] if e["domain"] == domain]
        if not rows:
            continue
        lines += [f"### {label}", "", "| Dataset | Rows | Cols | Last verified | Companion page | Schema | Download |", "|---|---:|---:|---|---|---|---|"]
        for e in rows:
            schema = f"[schema](../../../{e['schema_path']})" if e["schema_path"] else "—"
            fname = Path(e["path"]).name
            lines.append(
                f"| {e['title']} | {e['rows']:,} | {e['columns']} | {e['last_verified'] or '—'} | "
                f"[[{e['companion_page_slug']}]] | {schema} | [{fname}](../../../{e['path']}) |"
            )
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def splice_page(text: str, block: str) -> str:
    if START not in text or END not in text:
        raise SystemExit(f"FAIL: {PAGE.relative_to(ROOT)} lacks catalog markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def uncataloged_csvs(catalog: dict) -> list[str]:
    paths = {e["path"] for e in catalog["datasets"]}
    return sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "data").glob("*.csv") if p.relative_to(ROOT).as_posix() not in paths)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale or a curated CSV is uncataloged")
    args = parser.parse_args(argv)

    catalog = build_catalog()
    missing = uncataloged_csvs(catalog)
    if missing:
        print("FAIL: curated CSVs missing from catalog:\n  " + "\n  ".join(missing), file=sys.stderr)
        return 1
    payload = json.dumps(catalog, indent=2, ensure_ascii=False) + "\n"
    page_text = PAGE.read_text(encoding="utf-8")
    new_page = splice_page(page_text, render_block(catalog))

    if args.check:
        stale = []
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != payload:
            stale.append(OUTPUT.relative_to(ROOT).as_posix())
        if new_page != page_text:
            stale.append(PAGE.relative_to(ROOT).as_posix())
        if stale:
            print("FAIL: dataset catalog is stale (run scripts/build_dataset_catalog.py): " + ", ".join(stale), file=sys.stderr)
            return 1
        print(f"OK: dataset catalog current ({catalog['counts']['datasets']} datasets)")
        return 0

    OUTPUT.write_text(payload, encoding="utf-8")
    PAGE.write_text(new_page, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} and {PAGE.relative_to(ROOT)} ({catalog['counts']['datasets']} datasets)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
